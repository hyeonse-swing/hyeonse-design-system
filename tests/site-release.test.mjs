import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { copyReleases, prepareRelease } from '../scripts/site-release.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
test('site archive is the versioned public package with verifiable bytes and no workspace files', (t) => {
  const directory = mkdtempSync(resolve(tmpdir(), 'hds-public-package-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
  const manifest = prepareRelease(root, directory);
  assert.equal(manifest.name, pkg.name);
  assert.equal(manifest.version, pkg.version);
  assert.equal(manifest.file, `hyeonse-design-system-${pkg.version}.tgz`);
  assert.equal(manifest.url, `https://design-system.hyeonse.dev/releases/${manifest.file}`);
  const path = resolve(directory, manifest.file);
  const bytes = readFileSync(path);
  assert.equal(manifest.size, bytes.byteLength);
  assert.equal(manifest.sha256, createHash('sha256').update(bytes).digest('hex'));
  assert.equal(manifest.integrity, `sha512-${createHash('sha512').update(bytes).digest('base64')}`);
  const entries = execFileSync('tar', ['-tzf', path], { encoding: 'utf8' }).trim().split('\n');
  assert(entries.every(entry => entry.startsWith('package/') && !entry.split('/').includes('..')));
  assert(entries.every(entry => !/(?:^|\/)(?:\.env(?:\..*)?|\.git|\.vercel|\.site|node_modules|output|private|releases)(?:\/|$)/.test(entry)), 'No secrets, workspace, dependencies, or recursive archive');
  assert(entries.includes('package/dist/layout.js'));
  assert(entries.includes('package/dist/sizing.js'));
  assert(entries.includes('package/dist/catalog.json'));
  assert(entries.includes('package/licenses/base-ui-MIT.txt'));
  const shipped = JSON.parse(execFileSync('tar', ['-xOzf', path, 'package/package.json'], { encoding: 'utf8' }));
  assert.equal(shipped.version, manifest.version);
  assert.deepEqual(shipped.exports, pkg.exports);
  assert.equal(shipped.dependencies['@base-ui/react'], '1.9.0');
});

test('release store preserves previous versions and refuses same-version replacement', (t) => {
  const directory = mkdtempSync(resolve(tmpdir(), 'hds-release-store-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const fixture = resolve(directory, 'fixture');
  const store = resolve(directory, 'releases');
  const output = resolve(directory, '.site/releases');
  mkdirSync(fixture);
  const packagePath = resolve(fixture, 'package.json');
  const pkg = { name: '@hyeonse/design-system', version: '0.3.0', files: ['index.js'] };
  writeFileSync(packagePath, JSON.stringify(pkg));
  writeFileSync(resolve(fixture, 'index.js'), 'export const value = 3;\n');
  const previous = prepareRelease(fixture, store);
  const previousBytes = readFileSync(resolve(store, previous.file));
  pkg.version = '0.4.0';
  writeFileSync(packagePath, JSON.stringify(pkg));
  const current = prepareRelease(fixture, store);
  assert.deepEqual(prepareRelease(fixture, store), current);
  copyReleases(store, output, current);
  assert.deepEqual(readFileSync(resolve(output, previous.file)), previousBytes);
  assert(existsSync(resolve(output, current.file)));
  assert.equal(JSON.parse(readFileSync(resolve(output, 'manifest.json'), 'utf8')).version, '0.4.0');
  rmSync(resolve(directory, '.site'), { recursive: true });
  copyReleases(store, output, current);
  assert.deepEqual(readFileSync(resolve(output, previous.file)), previousBytes);
  const currentBytes = readFileSync(resolve(store, current.file));
  writeFileSync(resolve(fixture, 'index.js'), 'export const value = 4;\n');
  assert.throws(() => prepareRelease(fixture, store), /Immutable release 0\.4\.0 changed/);
  assert.deepEqual(readFileSync(resolve(store, current.file)), currentBytes);
  assert.deepEqual(readFileSync(resolve(store, previous.file)), previousBytes);
});
